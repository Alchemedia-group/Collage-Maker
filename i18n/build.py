#!/usr/bin/env python3
"""Generates the Android string resources from the English source and the translations.

  python3 i18n/build.py            writes app/src/main/res/values*/strings.xml and res/xml/locales_config.xml
Run it again after editing any of en.py, es.py, de.py, fr.py, it.py, pt.py, hi.py, id.py.
"""
import importlib, os, re, sys
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import en

RES = os.path.join(HERE, '..', 'app', 'src', 'main', 'res')
# language code in the source files -> (Android resource folder, BCP-47 tag for locales_config)
LANGS = [('es', 'values-es', 'es'), ('de', 'values-de', 'de'), ('fr', 'values-fr', 'fr'), ('it', 'values-it', 'it'),
         ('pt', 'values-pt', 'pt'), ('hi', 'values-hi', 'hi'), ('id', 'values-in', 'id')]


def android(text):
    """Escapes text for a strings.xml value."""
    t = escape(text)
    t = t.replace('\\', '\\\\').replace("'", "\\'").replace('"', '\\"')
    t = t.replace('\n', '\\n')
    if t != t.strip():
        t = '"' + t.replace('\\"', '"') .replace("\\'", "'") + '"'  # quoted values keep their spaces
    elif t.startswith(('@', '?')):
        t = '\\' + t
    return t


def string_entries(strings, layouts):
    for key, value in strings.items():
        yield key, value
    for lid, value in layouts.items():
        yield 'layout_' + lid, value


def write(folder, strings, layouts, plurals, translatable_app_name):
    d = os.path.join(RES, folder)
    os.makedirs(d, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by i18n/build.py from i18n/*.py. Do not edit by hand. -->', '<resources>']
    if translatable_app_name:
        lines.append('    <string name="app_name" translatable="false">Photo Collage</string>')
    for key, value in string_entries(strings, layouts):
        lines.append(f'    <string name="{key}">{android(value)}</string>')
    for key, forms in plurals.items():
        lines.append(f'    <plurals name="{key}">')
        for q in ('zero', 'one', 'two', 'few', 'many', 'other'):
            if q in forms:
                lines.append(f'        <item quantity="{q}">{android(forms[q])}</item>')
        lines.append('    </plurals>')
    lines.append('</resources>')
    with open(os.path.join(d, 'strings.xml'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')


def main():
    write('values', en.EN, en.LAYOUT_EN, en.PLURALS_EN, True)
    for code, folder, _ in LANGS:
        m = importlib.import_module(code)
        write(folder, m.T, m.L, m.P, False)
    xml_dir = os.path.join(RES, 'xml')
    os.makedirs(xml_dir, exist_ok=True)
    tags = ['en'] + [tag for _, _, tag in LANGS]
    with open(os.path.join(xml_dir, 'locales_config.xml'), 'w', encoding='utf-8') as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Languages shown in Android 13+ per-app language settings. -->\n<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n')
        for t in tags:
            f.write(f'    <locale android:name="{t}" />\n')
        f.write('</locale-config>\n')
    print('wrote', 1 + len(LANGS), 'string files and locales_config.xml')


if __name__ == '__main__':
    main()
